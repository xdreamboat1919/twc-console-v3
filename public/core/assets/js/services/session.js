function captureSessionState() {
  return {
    v: 9,
    fields: TWC.dataSource.captureFields(FIELDS),
    creatives: creatives,
    checked: checked,
    rtDone: rtDone,
    wfDone: wfDone,
    lkDone: lkDone,
    pfDone: pfDone,
    comp: COMP,
    pxOn: pxOn,
    pqOn: pqOn,
    dailyRecords: dailyRecords,
    optimizationActions: optimizationActions,
    changeRecords: changeRecords,
    experimentRecords: experimentRecords,
    scaleCandidates: scaleCandidates,
    scaleSteps: scaleSteps,
    creativeIdeas: creativeIdeas,
    creativeAssets: creativeAssets,
    workspaceState: typeof workspaceState === 'undefined' ? null : workspaceState,
  };
}
function applySessionState(d) {
  if (!d || typeof d !== 'object') throw new Error('Invalid console session');
  if (d.fields) TWC.dataSource.applyFields(FIELDS, d.fields);
  creatives = Array.isArray(d.creatives) ? d.creatives : [];
  checked = d.checked || {};
  rtDone = d.rtDone || {};
  wfDone = d.wfDone || {};
  lkDone = d.lkDone || {};
  pfDone = d.pfDone || {};
  dailyRecords = Array.isArray(d.dailyRecords) ? d.dailyRecords : [];
  optimizationActions = Array.isArray(d.optimizationActions) ? d.optimizationActions : [];
  changeRecords = Array.isArray(d.changeRecords) ? d.changeRecords : [];
  experimentRecords = Array.isArray(d.experimentRecords) ? d.experimentRecords : [];
  scaleCandidates = Array.isArray(d.scaleCandidates) ? d.scaleCandidates : [];
  scaleSteps = Array.isArray(d.scaleSteps) ? d.scaleSteps : [];
  creativeIdeas = Array.isArray(d.creativeIdeas) ? d.creativeIdeas : [];
  creativeAssets = Array.isArray(d.creativeAssets) ? d.creativeAssets : [];
  if (d.pxOn) pxOn = d.pxOn;
  if (d.pqOn) pqOn = d.pqOn;
  if (d.comp) {
    COMP.length = 0;
    d.comp.forEach((c) => {
      COMP.push(c);
    });
  }
  if (d.workspaceState && typeof workspaceState !== 'undefined')
    workspaceState = workspaceMigrate(d.workspaceState);
}

$('save').addEventListener('click', () => {
  var d = captureSessionState();
  dl(
    new Blob([JSON.stringify(d, null, 2)], { type: 'application/json' }),
    'twc-console-' + new Date().toISOString().slice(0, 10) + '.json',
  );
  if (TWC.store) TWC.store.saveNow('session export');
  toast('Session exported and workspace saved');
});
$('load').addEventListener('click', () => {
  $('file').click();
});
$('file').addEventListener('change', (e) => {
  var f = e.target.files[0];
  if (!f) return;
  var r = new FileReader();
  r.onload = () => {
    try {
      var d = JSON.parse(r.result);
      applySessionState(d);
      renderAll();
      if (typeof renderProductionAll === 'function') renderProductionAll();
      if (TWC.store) TWC.store.saveNow('session import');
      toast('Session imported and saved');
    } catch (err) {
      alert('That file could not be read as a console session.');
    }
  };
  r.readAsText(f);
  e.target.value = '';
});
